"""Tracking-overhead benchmark for entropylens (PyTorch, CPU only).

Measures what `EntropyTracker` costs per training step, in wall time and in
peak memory, on ReLU MLPs of three sizes and two batch sizes.

    python benchmarks/overhead.py            # full run, a few minutes
    python benchmarks/overhead.py --tiny --out-dir /some/dir   # smoke run

Writes results.csv (one row per configuration and mode) and results.md
(environment, method, tables) into --out-dir. Both files are generated;
never edit a number by hand.

Modes (one fresh process per configuration, mode and repeat):

* baseline: one optimiser step = zero_grad, forward, cross-entropy loss,
  backward, Adam step. No tracker attached. The timed interval is that step.
* tracked_every_step: the identical step with a default `EntropyTracker`
  attached (attached once, before warm-up), so every forward pass of every
  step is tracked. This is the worst case. The timed interval is that step.
* tracked_eval_forward: the pattern documented in the README. Each iteration
  runs one untimed baseline step, then the timed interval is: attach, one
  forward pass under `torch.no_grad()` on a batch of the same size, detach.
  The time reported is the cost of one such tracked pass, which a user pays
  once per epoch (or however often they choose to track).

The tracker is the default one, `EntropyTracker(model)`: every leaf layer is
hooked, bins=32. Linear layers get batch-wise entropy only, ReLU layers get
batch-wise and per-example entropy. A `layer_filter` would track fewer
layers and cost less; that is not measured here.

Timing: `time.perf_counter` around the timed interval; warm-up iterations
are run first and discarded. All timed steps of all repeats of one
(configuration, mode) are pooled; the median and the quartiles Q1 and Q3
(linear interpolation) are taken over that pool, and IQR = Q3 - Q1.
Overhead = tracked median - baseline median; relative overhead is that
difference divided by the baseline median. The order of the modes is
reversed on every other repeat, so slow drift (thermal, background load)
does not always hit the same mode.

Peak memory: `resource.getrusage(RUSAGE_SELF).ru_maxrss` read at the end of
each fresh process (bytes on macOS, kilobytes on Linux, normalised here).
It is the peak resident set size of the whole process: interpreter, torch,
model, data, optimiser state and tracker together. Only the difference
between two modes of the same configuration is informative, and it is
limited by run-to-run spread, which the tables show. `tracemalloc` is not
used: it does not see torch's native tensor memory.

History: `EntropyTracker.records` keeps one record per tracked layer per
tracked forward pass and never drops any. The benchmark leaves that as it
is (it is what a user gets), so peak memory includes the history of
warm-up + timed passes; its tensor payload is reported separately.

Not covered: GPU, conv layers, the TensorFlow and JAX backends, Windows
(no `resource` module). See the "Not measured" section of results.md.
"""
import argparse
import csv
import datetime
import json
import os
import platform
import resource
import statistics
import subprocess
import sys
import time
from pathlib import Path
from typing import Any

import numpy as np
import torch
from torch import nn

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
from entropylens.hooks import EntropyTracker

SEED = 0
THREADS = 4
IN_DIM, N_CLASSES, N_BATCHES = 32, 10, 4
MODELS: dict[str, tuple[int, int]] = {  # name -> (width, hidden layers)
    "small": (64, 2), "medium": (256, 3), "large": (512, 4)}
# Both are N >= 256, the batch size from which the README reports all probed
# adversarial cases of the batch-wise estimate within 5%.
BATCH_SIZES = (256, 1024)
MODES = ("baseline", "tracked_every_step", "tracked_eval_forward")
COLUMNS = (
    "model", "width", "hidden_layers", "parameters", "batch_size", "mode",
    "threads", "warmup_steps", "timed_steps", "repeats",
    "time_median_ms", "time_q1_ms", "time_q3_ms",
    "repeat_median_min_ms", "repeat_median_max_ms",
    "peak_rss_median_mb", "peak_rss_min_mb", "peak_rss_max_mb",
    "tracked_layers", "history_passes", "history_bytes")

Row = dict[str, Any]

# No hostname, username or path in here: results.md is committed and public.
TEMPLATE = """\
# Tracking overhead of entropylens (PyTorch, CPU)

Generated by `python benchmarks/overhead.py`. Do not edit by hand: rerun the
script. The same numbers, unformatted, are in `results.csv`.

## Environment

- Date: {date}
- CPU: {cpu}, {cores} logical cores
- OS: {os}
- Python {python}, torch {torch}, numpy {numpy}
- torch threads: {threads} (`torch.set_num_threads`), CPU only
- 1-minute load average when the run started: {load:.2f} (other processes
  were not stopped)

## Method

ReLU MLPs on synthetic data: standard-normal inputs with {in_dim} features,
{n_classes} random classes, {n_batches} fixed batches used in turn,
cross-entropy loss, Adam (lr 1e-3), seed {seed} for torch and numpy.

{models}

Batch sizes: {batches}. All are N ≥ 256, where the README reports that all
probed adversarial cases of the batch-wise estimate are off by less than 5%.
The benchmark measures cost only; it does not check the entropy values.

Three modes, each run in a fresh process:

- `baseline`: one optimiser step (zero_grad, forward, loss, backward, Adam
  step) with no tracker. The step is timed.
- `tracked_every_step`: the identical step with a default
  `EntropyTracker(model)` attached, so every forward pass is tracked. This is
  the worst case. The step is timed.
- `tracked_eval_forward`: the pattern in the README. After each untimed
  baseline step, one extra forward pass under `torch.no_grad()` with the
  tracker attached (attach, forward, detach) is timed. A user pays this once
  per epoch, or as often as they choose to track.

The tracker is the default one: every leaf layer is hooked (Linear layers:
batch-wise entropy; ReLU layers: batch-wise and per-example entropy), 32 bins.

Timing: `time.perf_counter`; {warmup} warm-up iterations discarded, then
{steps} timed iterations, in each of {repeats} fresh processes per
configuration and mode. The {pooled} timed values are pooled; the median and
the quartiles are taken over that pool, and IQR = Q3 − Q1. Overhead = tracked
median − baseline median; the percentage is relative to the baseline median.
The mode order is reversed on every other repeat so that drift does not
favour one mode. The spread of the per-repeat medians is in `results.csv`.

Peak memory: `ru_maxrss` (peak resident set size of the whole process,
normalised to MB) read at the end of each fresh process. It includes the
interpreter, torch, the model, the data and the optimiser state, so only the
difference between modes means anything, and it cannot be resolved below the
run-to-run spread. Python-level tools such as `tracemalloc` were not used
because they do not see torch's tensor memory.

History: `EntropyTracker.records` keeps one record per tracked layer per
tracked forward pass and never drops any. The benchmark does not clear it, so
the tracked peaks include the history of {passes} passes ({warmup} warm-up +
{steps} timed). Its tensor payload per pass is in the last column of the
memory table; it grows linearly with the number of tracked passes.

## Results

### Time, worst case: tracker attached on every training step

{every_step}

### Time, README pattern: one tracked no-grad forward pass

{eval_forward}

The last column is the tracked pass divided by the baseline step. With one
tracked pass per epoch of E steps, the added training time is that number
divided by E.

### Peak memory: process peak RSS in MB, median (min–max) over repeats

{memory}

"Within spread" marks a difference no larger than the min–max spread of
either side: it is not distinguishable from zero here.

## Not measured

- GPU (CUDA or MPS): CPU only.
- Conv layers and other 4D+ activations: the tracker skips them.
- The TensorFlow and JAX backends.
- A tracker restricted with `layer_filter`, non-default `bins`, the drop-in
  `Entropy*` layers, `confidence_interval` (bootstrap) and `entropylens.viz`.
- Other architectures, optimisers, thread counts and machines.
- History growth beyond the passes of this run, and the Python object
  overhead of the stored records.
- Windows (the script needs the `resource` module).
"""


def build_mlp(width: int, hidden_layers: int) -> nn.Sequential:
    layers: list[nn.Module] = []
    fan_in = IN_DIM
    for _ in range(hidden_layers):
        layers += [nn.Linear(fan_in, width), nn.ReLU()]
        fan_in = width
    return nn.Sequential(*layers, nn.Linear(fan_in, N_CLASSES))


def train_step(net: nn.Module, opt: torch.optim.Optimizer,
               x: torch.Tensor, y: torch.Tensor) -> None:
    opt.zero_grad()
    nn.functional.cross_entropy(net(x), y).backward()
    opt.step()


def history_bytes(records: dict[str, list[Any]]) -> int:
    """Tensor payload held in the tracker history (no Python object overhead)."""
    return sum(
        t.numel() * t.element_size()
        for recs in records.values() for rec in recs
        for part in (rec.batch, rec.per_example) if part is not None
        for t in vars(part).values() if isinstance(t, torch.Tensor))


def run_worker(model: str, batch: int, mode: str, warmup: int, steps: int) -> Row:
    """Measure one (configuration, mode) in this process; see module docstring."""
    torch.set_num_threads(THREADS)
    torch.manual_seed(SEED)
    rng = np.random.default_rng(SEED)
    net = build_mlp(*MODELS[model])
    xs = torch.from_numpy(
        rng.standard_normal((N_BATCHES, batch, IN_DIM), dtype=np.float32))
    ys = torch.from_numpy(rng.integers(0, N_CLASSES, (N_BATCHES, batch)))
    opt = torch.optim.Adam(net.parameters(), lr=1e-3)
    assert torch.get_num_threads() == THREADS
    assert all(t.device.type == "cpu" for t in (xs, ys, *net.parameters()))

    tracker = EntropyTracker(net)  # type: ignore[no-untyped-call]
    if mode == "tracked_every_step":
        tracker.attach()  # type: ignore[no-untyped-call]
    times_ms: list[float] = []
    for i in range(-warmup, steps):  # negative i = warm-up, not recorded
        x, y = xs[i % N_BATCHES], ys[i % N_BATCHES]
        if mode == "tracked_eval_forward":
            train_step(net, opt, x, y)
            start = time.perf_counter()
            tracker.attach()  # type: ignore[no-untyped-call]
            with torch.no_grad():
                net(x)
            tracker.detach()  # type: ignore[no-untyped-call]
        else:
            start = time.perf_counter()
            train_step(net, opt, x, y)
        elapsed = time.perf_counter() - start
        if i >= 0:
            times_ms.append(elapsed * 1e3)

    # ru_maxrss: bytes on macOS, kilobytes on Linux
    unit = 1 if sys.platform == "darwin" else 1024
    return {
        "times_ms": times_ms,
        "peak_rss_bytes": resource.getrusage(resource.RUSAGE_SELF).ru_maxrss * unit,
        "parameters": sum(p.numel() for p in net.parameters()),
        "tracked_layers": len(tracker.records),
        "history_passes": max((len(r) for r in tracker.records.values()), default=0),
        "history_bytes": history_bytes(tracker.records),
    }


def spawn_worker(job: Row) -> Row:
    """Run one job in a fresh interpreter, so ru_maxrss belongs to it alone."""
    proc = subprocess.run(
        [sys.executable, str(Path(__file__).resolve()), "--worker", json.dumps(job)],
        capture_output=True, text=True, check=False)
    if proc.returncode != 0:
        sys.exit(f"worker failed for {job}:\n{proc.stderr}")
    result: Row = json.loads(proc.stdout.splitlines()[-1])
    return result


def summarise(job: Row, runs: list[Row]) -> Row:
    pooled = [t for run in runs for t in run["times_ms"]]
    q1, median, q3 = statistics.quantiles(pooled, n=4, method="inclusive")
    repeat_medians = [statistics.median(run["times_ms"]) for run in runs]
    rss_mb = [run["peak_rss_bytes"] / 2**20 for run in runs]
    width, hidden_layers = MODELS[job["model"]]
    return {
        "model": job["model"], "width": width, "hidden_layers": hidden_layers,
        "parameters": runs[0]["parameters"], "batch_size": job["batch"],
        "mode": job["mode"], "threads": THREADS,
        "warmup_steps": job["warmup"], "timed_steps": job["steps"],
        "repeats": len(runs),
        "time_median_ms": round(median, 4),
        "time_q1_ms": round(q1, 4), "time_q3_ms": round(q3, 4),
        "repeat_median_min_ms": round(min(repeat_medians), 4),
        "repeat_median_max_ms": round(max(repeat_medians), 4),
        "peak_rss_median_mb": round(statistics.median(rss_mb), 2),
        "peak_rss_min_mb": round(min(rss_mb), 2),
        "peak_rss_max_mb": round(max(rss_mb), 2),
        "tracked_layers": runs[0]["tracked_layers"],
        "history_passes": runs[0]["history_passes"],
        "history_bytes": runs[0]["history_bytes"],
    }


def measure(models: list[str], batches: list[int],
            warmup: int, steps: int, repeats: int) -> list[Row]:
    jobs = [{"model": m, "batch": b, "mode": mode, "warmup": warmup, "steps": steps}
            for m in models for b in batches for mode in MODES]
    runs: list[list[Row]] = [[] for _ in jobs]
    for repeat in range(repeats):
        # reverse the mode order on odd repeats: drift must not favour one mode
        for start in range(0, len(jobs), len(MODES)):
            group = list(range(start, start + len(MODES)))
            for i in group if repeat % 2 == 0 else reversed(group):
                runs[i].append(spawn_worker(jobs[i]))
        print(f"repeat {repeat + 1}/{repeats} done", flush=True)
    return [summarise(job, job_runs) for job, job_runs in zip(jobs, runs)]


def cpu_model() -> str:
    if sys.platform == "darwin":
        return subprocess.run(
            ["sysctl", "-n", "machdep.cpu.brand_string"],
            capture_output=True, text=True, check=False).stdout.strip()
    try:
        for line in Path("/proc/cpuinfo").read_text().splitlines():
            if line.startswith("model name"):
                return line.split(":", 1)[1].strip()
    except OSError:
        pass
    return platform.processor() or platform.machine()


def table(header: list[str], body: list[list[str]]) -> str:
    lines = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    return "\n".join(lines + ["| " + " | ".join(cells) + " |" for cells in body])


def iqr(row: Row) -> str:
    return f"{row['time_q3_ms'] - row['time_q1_ms']:.3f}"


def rss(row: Row) -> str:
    return (f"{row['peak_rss_median_mb']:.1f} "
            f"({row['peak_rss_min_mb']:.1f}–{row['peak_rss_max_mb']:.1f})")


def rss_delta(base: Row, other: Row) -> str:
    delta = other["peak_rss_median_mb"] - base["peak_rss_median_mb"]
    spread = max(r["peak_rss_max_mb"] - r["peak_rss_min_mb"] for r in (base, other))
    return f"{delta:+.1f}" + (" (within spread)" if abs(delta) <= spread else "")


def render_markdown(rows: list[Row], load_at_start: float) -> str:
    """Every number in the tables comes from `rows`, i.e. from results.csv."""
    by_key = {(r["model"], r["batch_size"], r["mode"]): r for r in rows}
    configs = list(dict.fromkeys((r["model"], r["batch_size"]) for r in rows))
    models, every_step, eval_forward, memory = [], [], [], []
    for name in dict.fromkeys(m for m, _ in configs):
        r = by_key[(name, configs[0][1], "tracked_every_step")]
        models.append([name, str(r["width"]), str(r["hidden_layers"]),
                       str(r["parameters"]), str(r["tracked_layers"])])
    for name, batch in configs:
        base, step, fwd = (by_key[(name, batch, mode)] for mode in MODES)
        base_ms = base["time_median_ms"]
        overhead = step["time_median_ms"] - base_ms
        every_step.append([
            name, str(batch), f"{base_ms:.3f}", iqr(base),
            f"{step['time_median_ms']:.3f}", iqr(step),
            f"{overhead:.3f}", f"{100 * overhead / base_ms:.0f}"])
        eval_forward.append([
            name, str(batch), f"{fwd['time_median_ms']:.3f}", iqr(fwd),
            f"{base_ms:.3f}", f"{fwd['time_median_ms'] / base_ms:.1f}"])
        memory.append([
            name, str(batch), rss(base), rss(step), rss_delta(base, step),
            rss(fwd), rss_delta(base, fwd),
            f"{step['history_bytes'] / step['history_passes'] / 1024:.1f}"])

    warmup, steps, repeats = (
        rows[0]["warmup_steps"], rows[0]["timed_steps"], rows[0]["repeats"])
    return TEMPLATE.format(
        date=datetime.date.today().isoformat(), cpu=cpu_model(),
        cores=os.cpu_count(), os=platform.platform(),
        python=platform.python_version(), torch=torch.__version__,
        numpy=np.__version__, threads=THREADS, load=load_at_start,
        in_dim=IN_DIM, n_classes=N_CLASSES, n_batches=N_BATCHES, seed=SEED,
        batches=", ".join(dict.fromkeys(str(b) for _, b in configs)),
        warmup=warmup, steps=steps, repeats=repeats, pooled=steps * repeats,
        passes=warmup + steps,
        models=table(["Model", "Width", "Hidden layers", "Parameters",
                      "Tracked layers"], models),
        every_step=table(
            ["Model", "Batch", "Baseline median (ms)", "Baseline IQR (ms)",
             "Tracked median (ms)", "Tracked IQR (ms)", "Overhead (ms/step)",
             "Overhead (%)"], every_step),
        eval_forward=table(
            ["Model", "Batch", "Tracked pass median (ms)", "IQR (ms)",
             "Baseline step median (ms)", "Cost in baseline steps"],
            eval_forward),
        memory=table(
            ["Model", "Batch", "Baseline", "Every step", "Δ vs baseline",
             "README pattern", "Δ vs baseline", "History per pass (KB)"],
            memory))


def main() -> None:
    parser = argparse.ArgumentParser(description=(__doc__ or "").splitlines()[0])
    parser.add_argument("--out-dir", type=Path, default=Path(__file__).parent,
                        help="where results.csv and results.md are written")
    parser.add_argument("--tiny", action="store_true",
                        help="one small model, one batch size, 3 steps, 1 repeat")
    parser.add_argument("--worker", help=argparse.SUPPRESS)
    args = parser.parse_args()

    if args.worker:
        print(json.dumps(run_worker(**json.loads(args.worker))))
        return

    load_at_start = os.getloadavg()[0]
    if args.tiny:
        rows = measure(["small"], [BATCH_SIZES[0]], warmup=1, steps=3, repeats=1)
    else:
        rows = measure(list(MODELS), list(BATCH_SIZES),
                       warmup=5, steps=30, repeats=5)

    args.out_dir.mkdir(parents=True, exist_ok=True)
    with (args.out_dir / "results.csv").open("w", newline="") as fh:
        writer = csv.DictWriter(fh, fieldnames=COLUMNS, lineterminator="\n")
        writer.writeheader()
        writer.writerows(rows)
    (args.out_dir / "results.md").write_text(
        render_markdown(rows, load_at_start), encoding="utf-8", newline="\n")
    print(f"wrote results.csv and results.md ({len(rows)} rows)")


if __name__ == "__main__":
    main()
